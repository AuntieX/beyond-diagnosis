// Converts the plain https static.wixstatic.com URLs written by generate-images.mjs
// into proper wix:image://v1/<fileId>/<name>#originWidth=&originHeight= URIs, so the
// frontend's media.getScaledToFillImageUrl() can serve correctly-sized, next-gen-format
// images instead of the raw multi-MB generated PNGs (this was killing LCP).

import { execSync } from "node:child_process";
import fs from "node:fs";

const CONFIG = JSON.parse(fs.readFileSync("wix.config.json", "utf8"));
const SITE_ID = CONFIG.siteId;
const TOKEN = execSync(`npx @wix/cli@latest token --site "${SITE_ID}"`, {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "ignore"],
}).trim();

const BASE = "https://www.wixapis.com";

async function call(method, path, body) {
  const res = await fetch(BASE + path, {
    method,
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      "wix-site-id": SITE_ID,
      "Content-Type": "application/json",
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    json = { raw: text };
  }
  if (res.status >= 300) throw new Error(`${method} ${path} -> ${res.status}: ${JSON.stringify(json)}`);
  return json;
}

function toWixImageUri(url, width, height) {
  const fileId = url.split("/").pop();
  const name = encodeURIComponent(fileId.replace(/~mv2\.(png|jpg|jpeg)$/i, ".$1"));
  return `wix:image://v1/${fileId}/${name}#originWidth=${width}&originHeight=${height}`;
}

const ENTITY_DIMS = { width: 1376, height: 768 };

const CMS_SLOTS = [
  { collectionId: "WarningSigns", slug: "persistent-bloating-ovarian-cancer" },
  { collectionId: "WarningSigns", slug: "blood-in-stool-colorectal-cancer" },
  { collectionId: "WarningSigns", slug: "nipple-changes-breast-cancer" },
  { collectionId: "AccessGuides", slug: "colonoscopy-covered-under-45" },
  { collectionId: "AccessGuides", slug: "mammogram-without-referral" },
  { collectionId: "AccessGuides", slug: "genetic-counseling-insurance-denial" },
  { collectionId: "Articles", slug: "youre-too-young-dangerous-sentence" },
  { collectionId: "Articles", slug: "what-i-wish-i-knew-before-biopsy" },
  { collectionId: "Articles", slug: "five-minute-symptom-log" },
];

async function fixOne(slot) {
  const query = await call("POST", "/wix-data/v2/items/query", {
    dataCollectionId: slot.collectionId,
    query: { filter: { slug: slot.slug } },
  });
  const item = query?.dataItems?.[0];
  if (!item) throw new Error(`No item found for ${slot.collectionId}/${slot.slug}`);
  const current = item.data.heroImage;
  if (!current || current.startsWith("wix:image://")) {
    console.log(`SKIP ${slot.collectionId}/${slot.slug} (already fixed or empty)`);
    return;
  }
  const uri = toWixImageUri(current, ENTITY_DIMS.width, ENTITY_DIMS.height);
  const merged = { ...item.data, heroImage: uri };
  await call("PUT", `/wix-data/v2/items/${item.id}`, {
    dataCollectionId: slot.collectionId,
    dataItem: { data: merged },
  });
  console.log(`FIXED ${slot.collectionId}/${slot.slug}`);
}

await Promise.all(CMS_SLOTS.map(fixOne));

const siteImagesPath = "src/lib/site-images.ts";
const current = fs.readFileSync(siteImagesPath, "utf8");
const match = current.match(/HOMEPAGE_HERO_URL = "([^"]+)"/);
if (match && !match[1].startsWith("wix:image://")) {
  const uri = toWixImageUri(match[1], 1200, 896);
  fs.writeFileSync(
    siteImagesPath,
    `// Generated by scripts/generate-images.mjs — Wix AI hero image, imported to Wix Media.\nexport const HOMEPAGE_HERO_URL = ${JSON.stringify(uri)};\n`,
  );
  console.log(`FIXED homepage hero -> ${siteImagesPath}`);
} else {
  console.log("SKIP homepage hero (already fixed)");
}

console.log("\nDone.");
